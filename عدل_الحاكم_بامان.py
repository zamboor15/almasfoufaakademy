"""
تعديلُ ملفِّ فاضلَ بأمان — ⛔ ولا تقاطعَ مع جلساتِه.
=====================================================
شرطُ فاضل 6 تشرين الأوّل 2026: «موافق بشرط ان لاتتقاطع مع الجلسات
الاخرى».

⚖ والوعدُ لا يكفي — فقد تقاطعنا مرّتَين في يومٍ واحد:
  ① رفعتُ الرقمَ ثمّ كتبت جلستُه عندَ 22:13 فكبُرَ الملفُّ 41,287 بايتةً.
     نجا تبديلي لأنّ كتابتَها جاءت بعدَ قراءتي — **بالحظِّ لا بالبناء**.
  ② واختفى الملفُّ كلُّه عندَ 13:5x أثناءَ «نقلِ» ورشةٍ، فاستُرِدَّ من حرزي.

⟹ فكلُّ تعديلٍ يمرُّ من هنا، وهو **قارنْ-ثمّ-بدّلْ**:
   ① تُقاسُ البصمةُ والحجمُ قبلَ القراءة
   ② يُحرَزُ الملفُّ في موضعَين
   ③ يُعدَّلُ في الذاكرة
   ④ **تُقاسُ البصمةُ ثانيةً قبلَ الكتابة** — فإن تبدّلَت وُقِفَ العملُ
      ⛔ ولم تُكتَبْ بايتةٌ، ويُعادُ من جديدٍ على الحالِ الجديد
   ⑤ تُفحَصُ الشفرةُ بـesprima: ان كسرَ التعديلُ ما لم يكنْ مكسورا رُدَّ
   ⑥ ثمّ تُكتَبُ، وتُقاسُ البصمةُ بعدَها للتوثيق

الاستعمالُ من أداةٍ أخرى:

    from عدل_الحاكم_بامان import بدّل_بامان
    بدّل_بامان([(قديم1, جديد1), (قديم2, جديد2)], 'وصف العمل')
"""
import hashlib
import os
import re
import shutil
import sys

sys.stdout.reconfigure(encoding='utf-8', errors='replace')

جذر = os.path.dirname(os.path.abspath(__file__))
الحاكم = os.path.join('d:' + os.sep, 'drive_d_backup', 'لغة فاضل محدث',
                      '05_البيئة', 'فاضل_IDE.html')
بيت_الحرز = os.path.join(جذر, '_حرز_البيئة')


def بصمة_الحاكم():
    with open(الحاكم, 'rb') as ف:
        خام = ف.read()
    return hashlib.sha256(خام).hexdigest().upper()[:12], len(خام), خام


def حال_التحليل(نص):
    try:
        import esprima
    except ImportError:
        return None
    حال = []
    for كتلة in re.finditer(r'(?s)<script(?:\s[^>]*)?>(.*?)</script>', نص):
        جسم = كتلة.group(1)
        if not جسم.strip():
            continue
        try:
            esprima.parseScript(جسم)
            حال.append('OK')
        except Exception as ع:
            # ⚠ يُسقَطُ رقمُ السطرِ : التعديلُ يُزيحُه بلا كسر
            حال.append(re.sub(r'Line \d+: ', '', str(ع))[:60])
    return حال


def بدّل_بامان(تبديلات, وصف, مرّات=3):
    """
    تبديلات : قائمةُ (قديم , جديد) — وكلُّ قديمٍ يجبُ أن يرِدَ مرّةً واحدةً.
    يُعيدُ True إن كُتِبَ، و False إن وُقِفَ العملُ بلا كتابة.
    """
    for محاولة in range(1, مرّات + 1):
        if not os.path.exists(الحاكم):
            print('🔴 الحاكمُ غيرُ موجودٍ ⟹ وُقِفَ العمل')
            return False

        قبل_بصمة, قبل_حجم, خام = بصمة_الحاكم()
        نص = خام.decode('utf-8')
        print('  ① الحاكم قبل : %d بايتة · %s' % (قبل_حجم, قبل_بصمة))

        # ② حرزٌ في موضعَين
        os.makedirs(بيت_الحرز, exist_ok=True)
        اسم = 'فاضل_IDE_قبل_%s.html' % re.sub(r'[^\wء-ي]+', '_', وصف)[:40]
        shutil.copy2(الحاكم, os.path.join(بيت_الحرز, اسم))
        print('  ② حُرِزَ : %s' % اسم)

        # ③ التعديلُ في الذاكرة
        جديد_نص = نص
        for قديم, جديد in تبديلات:
            عدد = جديد_نص.count(قديم)
            if عدد != 1:
                print('🔴 المرساةُ وردَت %d مرّةً ⛔ لا واحدةً ⟹ وُقِفَ العمل' % عدد)
                print('   «%s…»' % قديم[:70].replace('\n', ' '))
                return False
            جديد_نص = جديد_نص.replace(قديم, جديد, 1)

        # ⑤ الشفرةُ لا تُكسَر
        قبل_تحليل, بعد_تحليل = حال_التحليل(نص), حال_التحليل(جديد_نص)
        if قبل_تحليل is None:
            print('  ⚠ esprima غير منصَّب ⟹ لم تُقابَلْ حالُ التحليل')
        elif قبل_تحليل != بعد_تحليل:
            print('🔴 التعديلُ كسرَ شفرةً لم تكنْ مكسورةً ⟹ وُقِفَ العمل')
            for i, (ق, د) in enumerate(zip(قبل_تحليل, بعد_تحليل), 1):
                if ق != د:
                    print('   كتلة %d : «%s» ⟹ «%s»' % (i, ق[:40], د[:40]))
            return False
        print('  ⑤ التحليلُ كما كان')

        # ④ قارنْ-ثمّ-بدّلْ : أتبدّلَ الحاكمُ وأنا أعمل؟
        الآن_بصمة, الآن_حجم, _ = بصمة_الحاكم()
        if الآن_بصمة != قبل_بصمة:
            print('  ⚠ تبدّلَ الحاكمُ أثناءَ عملي : %s ⟹ %s (%d ⟹ %d)'
                  % (قبل_بصمة, الآن_بصمة, قبل_حجم, الآن_حجم))
            if محاولة < مرّات:
                print('     ⛔ لم تُكتَبْ بايتةٌ ⟹ يُعادُ على الحالِ الجديد (%d/%d)'
                      % (محاولة + 1, مرّات))
                continue
            print('🔴 تبدّلَ ثلاثَ مرّاتٍ ⟹ الجلسةُ تكتبُ الآن ⛔ ولا أُزاحمُها')
            return False

        with open(الحاكم, 'wb') as ف:
            ف.write(جديد_نص.encode('utf-8'))
        بعد_بصمة, بعد_حجم, _ = بصمة_الحاكم()
        print('  ⑥ كُتِبَ : %d ⟹ %d بايتة (%+d) · %s'
              % (قبل_حجم, بعد_حجم, بعد_حجم - قبل_حجم, بعد_بصمة))
        return True
    return False


if __name__ == '__main__':
    ب, ح, _ = بصمة_الحاكم()
    print('حالُ الحاكم : %d بايتة · %s' % (ح, ب))
    print('⟸ هذه أداةٌ تُستوردُ ⛔ لا تُشغَّلُ وحدَها.')
