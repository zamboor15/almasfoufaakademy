# -*- coding: utf-8 -*-
"""
حارس رقم الاصدار — يمنع ان يُعرَض على صاحب البناء الاحدث «تحديث» الى اقدم.
=========================================================================
العلة المقيسة 29 ايلول 2026 — بسؤال فاضل:
  «ماذا فعلت لتظهر لي شريط التحديث الذي يعيد النسخة الحالية الحديثة الى
   نسخة اقدم؟ فالمفروض هذا يحدث بعد ايجاد نسخة اقدم وليس احدث.»

وما كان: رُفِع الرقم 7.2.0 ⟹ 8.0.0 في **نسخة النشر** وحدها، والحاكم بقي
7.2.0. فصار الرقم لصاقة تُلصَق عند النشر ⛔ لا صفة تولد مع البناء.
والمنشور كان حديده من 05:45 والحاكم حديده 19:21 ⟹ فالبنر يعرض اقدم.

⟹ القاعدة المسنونة : الرقم يولد في الحاكم ⛔ ولا يُلصَق عند النشر،
   والنشر يحمله كما هو. «لا حاكمان لشيء واحد».

الاستعمال:  python افحص_اصدار_البيئة.py      (يعمل تلقائيا في pre-push)
"""
import hashlib, json, os, re, sys

sys.stdout.reconfigure(encoding='utf-8', errors='replace')

جذر = os.path.dirname(os.path.abspath(__file__))
منشور = os.path.join(جذر, 'downloads', 'فاضل', 'فاضل_IDE.html')
بيان = os.path.join(جذر, 'downloads', 'version.json')
حاكم = os.path.join(r'd:\drive_d_backup', 'لغة فاضل محدث',
                    '05_البيئة', 'فاضل_IDE.html')

حقول = {
    'الاصدار':   r"فضل_الاصدار\s*=\s*'([^']*)'",
    'المقارَن':  r"فضل_اصدار_الموقع\s*=\s*'([^']*)'",
    'بصمة':      r"حديد_بصمة\s*=\s*'([^']*)'",
    'ولادة':     r"حديد_ولادة\s*=\s*'([^']*)'",
}


def اقرأ(مسار):
    """يستخرج حقول الاصدار من ملف بيئة، بلا تحميل الملف كله في الذاكرة مرتين."""
    if not os.path.exists(مسار):
        return None
    نص = open(مسار, 'rb').read().decode('utf-8', 'replace')
    return {ا: (م.group(1) if (م := re.search(ن, نص)) else None)
            for ا, ن in حقول.items()}


def رقما(v):
    ج = (v or '0').split('.')
    ق = [int(س) if س.isdigit() else 0 for س in ج] + [0, 0, 0]
    return ق[0] * 10000 + ق[1] * 100 + ق[2]


صرخات, تنبيهات = [], []
م = اقرأ(منشور)
ح = اقرأ(حاكم)

print('حارس رقم الاصدار')

if م is None:
    print('  ⛔ لا نسخة نشر في downloads')
    sys.exit(1)

# ── ① الرقمان في نسخة النشر يجب ان يتطابقا ─────────────────────────
if م['الاصدار'] != م['المقارَن']:
    صرخات.append('في نسخة النشر رقمان مختلفان : فضل_الاصدار=%s و فضل_اصدار_الموقع=%s'
                 % (م['الاصدار'], م['المقارَن']))

# ── ② وبيان الموقع يجب ان يحمل الرقم نفسه ──────────────────────────
if os.path.exists(بيان):
    ب = json.load(open(بيان, 'rb'))
    if ب.get('version') != م['الاصدار']:
        صرخات.append('version.json يقول %s ونسخة النشر تقول %s'
                     % (ب.get('version'), م['الاصدار']))
else:
    صرخات.append('version.json مفقود')

# ── ③ والاصل : الرقم يولد في الحاكم ⛔ ولا يُلصَق عند النشر ─────────
if ح is None:
    print('  ⟸ الحاكم غير متاح على هذا الحاسوب ⟹ فُحِص المنشور وحده')
else:
    if رقما(م['الاصدار']) > رقما(ح['الاصدار']):
        صرخات.append(
            'النشر يدّعي %s والحاكم %s ⟹ الرقم لُصِق عند النشر.\n'
            '       والاثر : من يشغّل الحاكم يرى «يتوفر اصدار جديد» فيُنزَّل الى اقدم.\n'
            '       الدواء : يُرفَع الرقم في الحاكم اولا، ثم يُبنى النشر منه'
            % (م['الاصدار'], ح['الاصدار']))
    # وتأخّر الموقع بناءً امر عادي بين الاصدارات ⟹ تنبيه لا ردّ.
    # والكذب وحده يُرَدّ : ان يدّعي النشر رقما فوق الحاكم.
    # ⟸ وسند البناء يكشف تبدّل نصّ الحاكم ولو لم يتبدّل حديده
    سند_م = os.path.join(جذر, '_سند_البناء.json')
    if os.path.exists(سند_م):
        س = json.load(open(سند_م, 'rb'))
        حالية = hashlib.sha256(open(حاكم, 'rb').read()).hexdigest().upper()[:12]
        if حالية != س.get('بصمة_الحاكم'):
            صرخات.append(
                'الحاكم تبدّل بعد البناء : %s ⟹ %s  (%d ⟹ %d بايتة)\n'
                '       ⟹ نسخة النشر لقطة قديمة : يُعاد بناؤها بـ ابن_البيئة_للنشر.py'
                % (س.get('بصمة_الحاكم'), حالية,
                   س.get('بايتات_الحاكم', 0), os.path.getsize(حاكم)))
    else:
        تنبيهات.append('لا سند بناء ⟹ لا يُعرَف من ايّ حال بُنيت نسخة النشر')

    if م['بصمة'] != ح['بصمة']:
        تنبيهات.append(
            'حديد النشر ليس حديد الحاكم : %s (%s) ⟸ منشور · %s (%s) ⟸ حاكم\n'
            '       ⟹ الموقع متأخّر بناءً : يُعاد بناؤه من الحاكم في الاصدار القادم'
            % (م['بصمة'], م['ولادة'], ح['بصمة'], ح['ولادة']))

print('  الحاكم : %s   حديده %s' % (ح['الاصدار'], ح['ولادة']) if ح else '')
print('  المنشور: %s   حديده %s' % (م['الاصدار'], م['ولادة']))
print()

for س in تنبيهات:
    print('   ⚠ ' + س)

if صرخات:
    print('\n  رُد الدفع — %d علة في الترقيم:\n' % len(صرخات))
    for س in صرخات:
        print('   🔴 ' + س)
    print('\n  ⛔ ولا يُعرَض «تحديث» على من يملك الاحدث — البنر يُخفَض لا يُرفَع.')
    sys.exit(1)

print('  ✅ رقم واحد في ثلاثة مواضع، وحديد النشر هو حديد الحاكم ⟹ يجوز الدفع')
sys.exit(0)
