def اسم_شخص(ر):
    """اسمٌ مُختلَقٌ للمرتبةِ ر — وطولُه يتفاوتُ كما تتفاوتُ الحقيقيّة."""
    اول = (_مؤنّث[(ر * 7) % len(_مؤنّث)] if ر % 3 == 0
           else _مذكّر[(ر * 5) % len(_مذكّر)])
    قطع = [اول, _اباء[(ر * 11) % len(_اباء)]]
    شكل = ر % 4                      # 0⟹اسمان · 1⟹ثلاثة · 2و3⟹اربعة
    if شكل >= 1:
        قطع.append(_اجداد[(ر * 13) % len(_اجداد)])
    if شكل >= 2:
        قطع.append(_عوائل[(ر * 17) % len(_عوائل)])
    return ' '.join(قطع)


def اسم_جهة(ر):
    return '%s %s' % (_انواع_الجهة[ر % len(_انواع_الجهة)],
                      _اسماء_الجهة[(ر * 5) % len(_اسماء_الجهة)])


def اسم_قسم(ر):
    return 'قسم %s' % _اسماء_القسم[(ر * 3) % len(_اسماء_القسم)]


def بدّل_الاشخاص(نص, re):
    """
    يبدّلُ اسماءَ الاشخاصِ الحقيقيّةِ ببدائلَ مُختلَقةٍ عندَ النشر.

    🔴 ثلاثُ علّاتٍ مقيسةٌ فى 6 تشرين الاوّل 2026، وكلُّ علّةٍ علّمَت قاعدة:

    ① «الاستبدالُ الاعمى» — كانَ يُستبدَلُ القيمةُ عاريةً فى كلِّ الملفِّ،
       وفى الوحداتِ «الحى» و«بلا» ⟹ فدهسَ `لوحة_الحديد_الحية` و
       `ضغط_بلا_ضغط` فانكسرَت البيئةُ وظهرَت «فارغةً من الامثلة».
    ② «مطاردةُ الصيغِ» — قُصِرَ التبديلُ على `(الاسم=…)` فنجا ما فى
       `DYN-…|الاسم|` ثمّ `(اسم=…)` بلا «ال» ثمّ `(10=…)` ثمّ
       `طبع:1(الاسم)` — وكلَّما سُدَّت صيغةٌ ظهرَت اخرى.
    ③ ⟹ والقاعدةُ الجامعة : **المعرِّفُ فى الشفرةِ لا يحوى مسافةً.**
         · قيمةٌ فيها مسافةٌ (كلمتانِ فاكثر) ⟹ تُبدَّلُ فى كلِّ موضعٍ
           بامان، فلا تصادمَ مع اسمِ متغيّرٍ ولا دالّةٍ.
         · قيمةٌ مفردةٌ ⟹ تُبدَّلُ فى صيغةِ حقلِها وحدَها ⛔ لا عاريةً.
       وشاهدُ التحليلِ فى الباني يَشهَدُ على هذا بعدَ كلِّ بناء.
    """
    خريطة, عداد, احصاء = {}, {'شخص': 0, 'جهة': 0, 'قسم': 0}, {}

    def بديل_لـ(قيمة, نوع):
        if قيمة not in خريطة:
            مولّد = {'شخص': اسم_شخص, 'جهة': اسم_جهة, 'قسم': اسم_قسم}[نوع]
            خريطة[قيمة] = مولّد(عداد[نوع])
            عداد[نوع] += 1
        return خريطة[قيمة]

    # ── ① تُجمَعُ القيمُ من صيغتَيها المعروفتَين ────────────────────
    أنواع = {'الاسم': 'شخص', 'اسم': 'شخص', 'الوحدة': 'جهة',
             'وحدة': 'جهة', 'القسم': 'قسم', 'قسم': 'قسم'}
    for حقل, نوع in أنواع.items():
        for قيمة in re.findall(r'\(%s=([^)=]{2,70})\)' % حقل, نص):
            بديل_لـ(قيمة.strip(), نوع)
    for قيمة in re.findall(
            r'DYN-[A-Z]{3}-[A-Z]{3}-[A-Za-z0-9\-]{0,45}\|([^|]{4,70})\|', نص):
        بديل_لـ(قيمة.strip(), 'شخص')

    # ── ② ما فيه مسافةٌ يُبدَّلُ فى كلِّ موضعٍ — الاطولُ اوّلا ───────
    مركّبة = [ق for ق in خريطة if ' ' in ق and len(ق) >= 6]
    for ق in sorted(مركّبة, key=len, reverse=True):
        نص = نص.replace(ق, خريطة[ق])
    احصاء['مركّبة (كل موضع)'] = len(مركّبة)

    # ── ③ والمفردةُ فى صيغةِ حقلِها وحدَها ⛔ لا عاريةً ─────────────
    مفردة = {ق: ب for ق, ب in خريطة.items() if ق not in set(مركّبة)}

    def بدّل_حقلا(م):
        return '(%s=%s)' % (م.group(1), مفردة.get(م.group(2).strip(), م.group(2)))

    نص = re.sub(r'\((الاسم|اسم|الوحدة|وحدة|القسم|قسم)=([^)=]{2,70})\)',
                بدّل_حقلا, نص)
    احصاء['مفردة (فى حقلها)'] = len(مفردة)
    احصاء['قيم فريدة'] = len(خريطة)

    # ── ④ جهةُ عملِ فاضل باشكالِها ⟸ نُزِعَت بامرِه ──────────────────
    for قديم, جديد in (
            ('مديرية اتصالات واسط للمؤهلات والتقييم الاداري',
             'دائرة المؤهلات والتقييم الاداري'),
            ('مدير مديرية اتصالات ومعلوماتية واسط', 'مدير الدائرة'),
            ('مديرية اتصالات ومعلوماتية واسط', 'دائرة النهرين'),
            ('مديرية اتصالات واسط', 'دائرة النهرين'),
            ('مديرية الاتصالات وتكنولوجيا المعلومات', 'الدائرة'),
            ('مديرية الاتصالات', 'الدائرة')):
        نص = نص.replace(قديم, جديد)

    return نص, احصاء
