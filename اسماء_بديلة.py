def اسم_شخص(ر):
    """اسمٌ مُختلَقٌ للمرتبةِ ر — وطولُه يتفاوتُ كما تتفاوتُ الحقيقيّة."""
    اول = (_مؤنّث[(ر * 7) % len(_مؤنّث)] if ر % 3 == 0
           else _مذكّر[(ر * 5) % len(_مذكّر)])
    قطع = [اول, _اباء[(ر * 11) % len(_اباء)]]
    شكل = ر % 4                      # 0⟹اسمان · 1⟹ثلاثة · 2و3⟹اربعة
    if شكل >= 1:
        قطع.append(_اجداد[(ر * 13) % len(_اجداد)])
    if شكل >= 2:
        قطع.append(_عوائل[(ر * 17) % len(_عوائل)])
    return ' '.join(قطع)


def اسم_جهة(ر):
    return '%s %s' % (_انواع_الجهة[ر % len(_انواع_الجهة)],
                      _اسماء_الجهة[(ر * 5) % len(_اسماء_الجهة)])


def اسم_قسم(ر):
    return 'قسم %s' % _اسماء_القسم[(ر * 3) % len(_اسماء_القسم)]


def بدّل_الاشخاص(نص, re):
    """
    يبدّلُ (الاسم=…) و(الوحدة=…) و(القسم=…) ببديلٍ مُختلَق.

    🔴 العلّةُ المقيسةُ 6 تشرين الاوّل 2026 — «الاستبدالُ الاعمى»:
      كانَ التبديلُ يستبدلُ **القيمةَ عاريةً** فى كلِّ الملفِّ. وكانَ فى
      الوحداتِ «الحى» و«بلا» ⟹ فدهسَ:
          window.لوحة_الحديد_الحية  ⟸ صارَ  لوحة_الحديد_مجمع الوفاءة
          function ضغط_بلا_ضغط(     ⟸ صارَ  ضغط_وحدة الفرات 3_ضغط(
      فانكسرَت كتلتانِ من خمسٍ، وظهرَت البيئةُ «فارغةً من الامثلة».
    ⟹ فالتبديلُ مقصورٌ على **صيغةِ الحقلِ كاملةً** `(الحقل=القيمة)`
      ⛔ ولا تُمَسُّ القيمةُ عاريةً ابدا.
    """
    احصاء, خريطة = {}, {}
    for حقل, مولّد in (('الاسم', اسم_شخص), ('الوحدة', اسم_جهة), ('القسم', اسم_قسم)):
        قيم = re.findall(r'\(%s=([^)]{2,70})\)' % حقل, نص)
        جديدة = [ق for ق in dict.fromkeys(قيم) if (حقل, ق) not in خريطة]
        for ر, ق in enumerate(جديدة):
            خريطة[(حقل, ق)] = مولّد(ر)
        احصاء[حقل] = (len(قيم), len(جديدة))

    # ⚠ وقد يتكرّرُ البديلُ لو جاوزَ العددُ سعةَ التوافيق ⟹ يُفَضُّ بلاحقةٍ
    مستعمل, نهائية = {}, {}
    for مفتاح, بديل in خريطة.items():
        if بديل in مستعمل:
            مستعمل[بديل] += 1
            بديل = '%s %d' % (بديل, مستعمل[بديل])
        else:
            مستعمل[بديل] = 1
        نهائية[مفتاح] = بديل

    # 🔴 التبديلُ بالصيغةِ كاملةً ⛔ لا بالقيمةِ عاريةً
    def بدّل(م):
        حقل, قيمة = م.group(1), م.group(2)
        return '(%s=%s)' % (حقل, نهائية.get((حقل, قيمة), قيمة))

    نص = re.sub(r'\((الاسم|الوحدة|القسم)=([^)]{2,70})\)', بدّل, نص)
    return نص, احصاء
